import {docentGrantEvidence} from '../src/docent-grant-evidence.js';
import {SEED_HELPERS} from '../src/staff-data.js';
import {placeOverview,evidenceText} from '../src/place-evidence.js';
// Deterministic, public-only server bundle. No live sources or identity records.
import {ROOMS} from '../src/data.js';
import benchmarkCatalog from '../supabase/functions/ai-proxy/catalog-v9.js';
import {createHash} from 'node:crypto';
import {writeFile,readFile} from 'node:fs/promises';
const r=ROOMS.boycott;
const versions=r.versions.filter(v=>!v.verified).map(v=>({id:v.id,rank:v.rank,minAge:v.minAge,content:v.content,blocks:[...v.blocks,placeOverview({...r,content:v.content}),docentGrantEvidence(SEED_HELPERS.find(a=>a.id==='docent-silver'),{scope:'look',expires:null},{...r,content:v.content})].filter(Boolean).map(b=>({id:b.id,type:b.type,importance:b.importance,body:evidenceText(b),content:b.content??v.content,authorDisplay:'real',trust:b.trust??{},sources:(b.sources??[]).map(s=>({label:s.label,status:s.status??'to verify'}))}))}));
const payload={placeId:'boycott',versions,components:benchmarkCatalog.components};
const revision=createHash('sha256').update(JSON.stringify(payload)).digest('hex');
const contents='// Generated by scripts/build-ai-catalog.mjs; public exhibit evidence and synthetic benchmark kit.\nexport default '+JSON.stringify({revision,...payload},null,2)+';\n';
const path=new URL('../supabase/functions/ai-proxy/catalog.js',import.meta.url);
if(process.argv.includes('--check')) {if(await readFile(path,'utf8')!==contents)throw new Error('Stale AI catalog');} else await writeFile(path,contents);

const clientPath=new URL('../src/ai-catalog-revision.js',import.meta.url);
const client='// Generated public catalog revision; no server configuration.\nexport const AI_CATALOG_REVISION='+JSON.stringify(revision)+';\n';
if(process.argv.includes('--check')){if(await readFile(clientPath,'utf8')!==client)throw new Error('Stale client catalog revision');}else await writeFile(clientPath,client);

// Shared question policy: one implementation in the browser and deployed bundle.
const policy=await readFile(new URL('../src/boycott-question-policy.js',import.meta.url),'utf8');
const policyPath=new URL('../supabase/functions/ai-proxy/boycott-question-policy.js',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(policyPath,'utf8')!==policy)throw new Error('Stale Docent question policy');}else await writeFile(policyPath,policy);
